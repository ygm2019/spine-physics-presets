'use strict';
const { _electron: electron } = require('playwright-core');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const output = path.resolve(process.env.SPINE_TEST_OUTPUT || path.join(root, '.preset-library-output'));
const report = { mode: process.argv[2] ? 'packaged-exe' : 'development', checks: [], errors: [] };
let app;
async function main() {
  await fs.mkdir(output, { recursive: true });
  const env = { ...process.env, SPINE_PHYSICS_TEST: '1', SPINE_PHYSICS_TEST_DATA: path.join(output, 'profile-' + Date.now()) };
  delete env.ELECTRON_RUN_AS_NODE;
  app = await electron.launch({ executablePath: process.argv[2] || require('electron'), args: process.argv[2] ? [] : [root], env, timeout: 60000 });
  const page = await app.firstWindow();
  page.on('pageerror', e => report.errors.push(e.message));
  await page.waitForFunction(() => window.__spineTool);
  const fixture = JSON.parse(await fs.readFile(path.join(root, 'tests/fixtures/demo-43.json'), 'utf8'));
  const names = () => page.locator('#presetList .preset-btn').evaluateAll(items => items.map(b => b.dataset.presetName));
  const presets = () => page.evaluate(() => JSON.parse(localStorage.getItem('spineRigTools.physicsPresets.v1')));
  const preset = name => page.locator('[data-preset-name=' + JSON.stringify(name) + ']');
  const menu = id => page.locator('#presetMenu [data-action="' + id + '"]');
  const data = () => page.evaluate(() => window.__spineTool.getData());
  const confirm = () => page.locator('dialog .primary').click();
  const cancelDialog = () => page.locator('dialog button').filter({ hasText: '取消' }).click();
  const reload = async () => { await page.reload(); await page.waitForFunction(() => window.__spineTool); };
  const load = async () => {
    await page.evaluate(d => window.__spineTool.loadSkeleton(d, 'preset-library.json'), fixture);
    await page.waitForFunction(() => window.__spineTool.runtime.active);
    await page.locator('[data-constraint-name="head_physics"]').click();
  };
  const beginDrag = async (from, to, before = true) => {
    const a = await preset(from).boundingBox(), b = await preset(to).boundingBox();
    assert(a && b);
    await page.mouse.move(a.x + a.width / 2, a.y + a.height / 2);
    await page.mouse.down();
    await page.mouse.move(b.x + b.width * (before ? 0.2 : 0.8), b.y + b.height / 2, { steps: 8 });
  };
  const original = await names(), [a, b, c] = original;
  const importLibrary = async payload => {
    await page.evaluate(payload => { document.querySelector('#toast').textContent=''; window.__spineTool.importPresetFile(new File([JSON.stringify(payload)],'boundary-presets.json')); }, payload);
    await page.waitForFunction(() => document.querySelector('#toast').textContent.includes('预设库未导入') || document.querySelector('#toast').textContent.includes('导入完成'));
  };
  const storedBefore = await page.evaluate(() => localStorage.getItem('spineRigTools.physicsPresets.v1'));
  for(const invalid of [
    [{name:123,values:{wind:7}},{name:'123',values:{wind:9}}],
    [{name:'duplicate',values:{}},{name:'duplicate',values:{wind:9}}],
    [{name:'   ',values:{}}], [{name:'bad',values:[]}], [null], null
  ]) {
    await importLibrary(invalid);
    assert.match(await page.locator('#toast').textContent(),/预设库未导入/);
    assert.deepEqual(await names(),original);
    assert.equal(await page.evaluate(() => localStorage.getItem('spineRigTools.physicsPresets.v1')),storedBefore);
  }
  const invalidStored=JSON.stringify([{name:123,values:{wind:7}},{name:'123',values:{wind:9}}]);
  await page.evaluate(raw=>localStorage.setItem('spineRigTools.physicsPresets.v1',raw),invalidStored);await reload();
  assert.deepEqual(await names(),[]);
  assert.match(await page.locator('#toast').textContent(),/本地预设库无效/);
  assert.equal(await page.evaluate(()=>localStorage.getItem('spineRigTools.physicsPresets.v1')),invalidStored);
  await importLibrary([{name:'recovered',values:{wind:3}}]);
  assert.equal(await page.evaluate(()=>localStorage.getItem('spineRigTools.physicsPresets.v1.invalidBackup')),invalidStored);
  assert.deepEqual(await names(),['recovered']);
  await page.evaluate(()=>localStorage.removeItem('spineRigTools.physicsPresets.v1'));await reload();
  assert.deepEqual(await names(),original);
  report.checks.push('rejects numeric/duplicate/blank identities and malformed values atomically; corrupt local bytes preserved and backed up on recovery');
  await load();
  const before = await data(), form = await page.evaluate(() => window.__spineTool.valuesFromForm());
  await preset(a).click({ button: 'right' });
  assert.deepEqual(await page.locator('#presetMenu button span').allTextContents(), ['删除', '复制', '重命名']);
  assert.deepEqual(await data(), before);
  assert.deepEqual(await page.evaluate(() => window.__spineTool.valuesFromForm()), form);
  await page.keyboard.press('Escape');
  await beginDrag(c, a);
  assert.equal(await page.locator('#presetList .drop-before').count(), 1);
  const marker = await page.locator('#presetList .drop-before').evaluate(el => ({ border: getComputedStyle(el).borderLeftColor, shadow: getComputedStyle(el).boxShadow }));
  assert.equal(marker.border, 'rgb(242, 201, 76)');
  assert.match(marker.shadow, /rgb\(242, 201, 76\)/);
  assert.deepEqual(await data(), before, 'drag must not apply before release');
  await page.screenshot({ path: path.join(output, 'preset-insertion.png') });
  await page.mouse.up();
  assert.deepEqual(await names(), [c, a, b]);
  assert.deepEqual((await presets()).map(p => p.name), [c, a, b]);
  assert.deepEqual(await data(), before, 'release must not apply preset');
  assert.deepEqual(await page.evaluate(() => window.__spineTool.valuesFromForm()), form);
  await beginDrag(c, b, false); await page.mouse.up();
  assert.deepEqual(await names(), original);
  await beginDrag(c, a); await page.keyboard.press('Escape'); await page.mouse.up();
  assert.deepEqual(await names(), original);
  const aBox = await preset(a).boundingBox();
  await page.mouse.move(aBox.x + aBox.width / 2, aBox.y + aBox.height / 2); await page.mouse.down();
  await page.keyboard.press('Escape'); await page.mouse.up();
  assert.deepEqual(await data(), before, 'Escape during pending click must not apply preset');
  await beginDrag(c, a);
  const outside = await page.locator('.preview-stage').boundingBox();
  await page.mouse.move(outside.x + outside.width / 2, outside.y + outside.height / 2); await page.mouse.up();
  assert.deepEqual(await names(), original);
  await beginDrag(c, a);
  await page.locator('#presetList').dispatchEvent('pointercancel', { pointerId: 1 }); await page.mouse.up();
  assert.deepEqual(await names(), original);
  await beginDrag(c, a); await page.mouse.up(); await reload();
  assert.deepEqual(await names(), [c, a, b]);
  report.checks.push('left-drag both directions, insertion marker, no preset apply, Escape/outside/cancel and reload persistence');

  await load();
  await preset(a).click();
  const applied = await data(), values = await page.evaluate(() => window.__spineTool.valuesFromForm());
  const baseValues = (await presets()).find(p => p.name === a).values;
  await preset(b).click({ button: 'right' });
  assert.equal(await preset(a).evaluate(el => el.classList.contains('selected')), true);
  await menu('copy').click();
  assert.deepEqual(await data(), applied);
  assert.deepEqual(await page.evaluate(() => window.__spineTool.valuesFromForm()), values);
  const copyName = b + ' 副本';
  await preset(b).click({ button: 'right' }); await menu('copy').click();
  assert.equal((await names()).includes(copyName + '_2'), true);
  await preset(a).click({ button: 'right' }); await menu('rename').click();
  await page.locator('dialog input').fill(b); await confirm();
  assert.equal((await names()).includes(a), true, 'duplicate rename rejected');
  await preset(a).click({ button: 'right' }); await menu('rename').click();
  await page.locator('dialog input').fill('   '); await confirm();
  assert.equal((await names()).includes(a), true, 'blank rename rejected');
  await preset(a).click({ button: 'right' }); await menu('rename').click();
  await page.locator('dialog input').fill('已取消'); await cancelDialog();
  assert.equal((await names()).includes(a), true);
  const renamed = '头发 "柔软" <预设>';
  await preset(a).click({ button: 'right' }); await menu('rename').click();
  await page.locator('dialog input').fill(renamed); await page.keyboard.press('Enter');
  assert.equal(await preset(renamed).evaluate(el => el.classList.contains('selected')), true);
  assert.deepEqual(await data(), applied, 'rename does not alter already applied constraints');
  await page.evaluate(v => window.__spineTool.setForm({ ...v, wind: -720, mix: 2.2 }), baseValues);
  await page.locator('#savePreset').click();
  assert.equal((await presets()).find(p => p.name === renamed).values.wind, -720);
  assert.equal((await presets()).some(p => p.name === a), false);
  const sourceValues = (await presets()).find(p => p.name === b).values;
  await preset(copyName).click();
  await page.locator('#f_wind').fill('-930'); await page.locator('#savePreset').click();
  assert.equal((await presets()).find(p => p.name === copyName).values.wind, -930);
  assert.deepEqual((await presets()).find(p => p.name === b).values, sourceValues, 'copies are independent');
  const state = await data();
  await preset(b).click({ button: 'right' }); await menu('delete').click(); await cancelDialog();
  assert.equal((await names()).includes(b), true);
  await preset(b).click({ button: 'right' }); await menu('delete').click(); await confirm();
  assert.equal((await names()).includes(b), false);
  assert.deepEqual(await data(), state, 'deleting preset leaves applied constraints intact');
  report.checks.push('right menu never applies; unique deep copies, blank/duplicate/cancel rename, selected rename/save and safe text, delete confirmation');

  const expected = await presets();
  const exportPath = path.join(output, 'presets.json');
  await app.evaluate(({ dialog }, filePath) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath }); }, exportPath);
  await page.locator('#exportPresets').click();
  await page.waitForFunction(() => document.querySelector('#toast').textContent.includes('已保存 JSON'));
  assert.deepEqual(JSON.parse(await fs.readFile(exportPath, 'utf8')).presets, expected);
  await reload(); assert.deepEqual(await presets(), expected);
  for (const size of [{ width: 1440, height: 900 }, { width: 1060, height: 760 }]) {
    await app.evaluate(({ BrowserWindow }, size) => BrowserWindow.getAllWindows()[0].setSize(size.width, size.height), size);
    await preset(renamed).click({ button: 'right' });
    const bounds = await page.evaluate(() => { const r = document.querySelector('#presetMenu').getBoundingClientRect(); return { left: r.left, top: r.top, right: r.right, bottom: r.bottom, w: innerWidth, h: innerHeight }; });
    assert(bounds.left >= 0 && bounds.top >= 0 && bounds.right <= bounds.w && bounds.bottom <= bounds.h);
    await page.screenshot({ path: path.join(output, 'preset-menu-' + size.width + '.png') });
    await page.keyboard.press('Escape');
  }
  const extras = Array.from({ length: 20 }, (_, i) => ({ name: '多行预设长名称-' + i, values: { wind: i } }));
  await page.evaluate(items => window.__spineTool.importPresetFile(new File([JSON.stringify({ presets: items })], 'many-presets.json')), extras);
  await page.waitForFunction(count => document.querySelectorAll('#presetList .preset-btn').length === count, expected.length + extras.length);
  const many = await names(), sourceName = many[0], lastName = many[many.length - 1];
  const sourceBox = await preset(sourceName).boundingBox(), listBox = await page.locator('#presetList').boundingBox();
  await page.mouse.move(sourceBox.x + sourceBox.width / 2, sourceBox.y + sourceBox.height / 2); await page.mouse.down();
  await page.mouse.move(listBox.x + listBox.width - 14, listBox.y + listBox.height - 3, { steps: 8 });
  await page.waitForFunction(() => { const el = document.querySelector('#presetList'); return el.scrollTop >= el.scrollHeight - el.clientHeight - 1; });
  const lastBox = await preset(lastName).boundingBox();
  await page.mouse.move(lastBox.x + lastBox.width * 0.8, lastBox.y + lastBox.height / 2, { steps: 4 }); await page.mouse.up();
  assert.deepEqual(await names(), [...many.slice(1), sourceName]);
  assert.deepEqual((await presets()).map(p => p.name), [...many.slice(1), sourceName]);
  await reload(); assert.deepEqual(await names(), [...many.slice(1), sourceName]);
  report.checks.push('wrapped preset rows, edge auto-scroll to hidden item, precise insertion and persistent order');
  for (const name of await names()) { await preset(name).click({ button: 'right' }); await menu('delete').click(); await confirm(); }
  assert.deepEqual(await presets(), []);
  await reload(); assert.deepEqual(await names(), []); assert.deepEqual(await presets(), []);
  assert.equal(await page.locator('#presetList .empty-state').count(), 1);
  report.checks.push('native export exact order/values; full/minimum menu bounds; empty library survives restart');
  assert.deepEqual(report.errors, []);
  report.passed = true;
}
main().catch(e => { report.passed = false; report.failure = e.stack; process.exitCode = 1; }).finally(async () => {
  if (app) await app.close().catch(() => {});
  await fs.mkdir(output, { recursive: true });
  await fs.writeFile(path.join(output, 'preset-library-report.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
});