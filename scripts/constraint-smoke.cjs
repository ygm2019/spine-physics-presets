'use strict';
const { _electron: electron } = require('playwright-core');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const output = path.resolve(process.env.SPINE_TEST_OUTPUT || path.join(root, '.constraint-output'));
const packaged = process.argv[2];
let app;
const report = { checks: [], errors: [], mode: packaged ? 'packaged-exe' : 'development' };
async function main() {
  await fs.mkdir(output, { recursive: true });
  const env = { ...process.env, SPINE_PHYSICS_TEST: '1', SPINE_PHYSICS_TEST_DATA: path.join(output, 'profile-' + Date.now()) };
  delete env.ELECTRON_RUN_AS_NODE;
  app = await electron.launch({ executablePath: packaged || require('electron'), args: packaged ? [] : [root], env, timeout: 60000 });
  const page = await app.firstWindow();
  page.on('pageerror', e => report.errors.push(e.message));
  await page.waitForFunction(() => window.__spineTool);
  const list = page.locator('#constraintList');
  const row = name => page.locator('[data-constraint-name="' + name + '"]');
  const menu = action => page.locator('#constraintMenu [data-action="' + action + '"]');
  const confirm = () => page.locator('dialog .primary').click();
  const beginDrag = async (from, to, before = true) => {
    const a = await from.boundingBox(), b = await to.boundingBox();
    assert(a && b, 'drag source and destination must be visible');
    await page.mouse.move(a.x + a.width / 2, a.y + a.height / 2);
    await page.mouse.down();
    await page.mouse.move(b.x + b.width / 2, b.y + b.height * (before ? 0.25 : 0.75), { steps: 8 });
  };
  const dragPointer = async (from, to, before = true) => {
    await beginDrag(from, to, before);
    await page.mouse.up();
  };
  const preset = name => page.locator('[data-preset-name="' + name + '"]');
  const presetOrder = () => page.evaluate(() => JSON.parse(localStorage.getItem('spineRigTools.physicsPresets.v1')).map(p => p.name));
  const presetCount = () => page.locator('#presetList [data-preset-name]').count();
  const presetMenu = action => page.locator('#presetMenu [data-action="' + action + '"]');
  assert.equal(await presetCount(), 3);
  const firstPreset = (await page.locator('#presetList [data-preset-name]').first().getAttribute('data-preset-name'));
  await preset(firstPreset).click({ button: 'right' });
  assert.deepEqual(await page.locator('#presetMenu button span').allTextContents(), ['删除', '复制', '重命名']);
  await presetMenu('copy').click();
  assert.equal(await presetCount(), 4);
  const copyName = firstPreset + ' 副本';
  assert.equal((await presetOrder()).includes(copyName), true);
  await preset(copyName).click({ button: 'right' });
  await presetMenu('rename').click();
  await page.locator('dialog input').fill('临时预设');
  await page.keyboard.press('Enter');
  assert.equal((await presetOrder()).includes('临时预设'), true);
  await preset('临时预设').click({ button: 'right' });
  await presetMenu('delete').click();
  await confirm();
  assert.equal((await presetOrder()).includes('临时预设'), false);
  report.checks.push('preset right-click copy, rename, delete and local persistence');
  for (const minor of [2, 3]) {
    const fixture = JSON.parse(await fs.readFile(path.join(root, `tests/fixtures/demo-4${minor}.json`), 'utf8'));
    const head = (fixture.physics || fixture.constraints)[0];
    head.order = 3;
    head.wind = -250;
    head.mix = 1.8;
    head.windGlobal = true;
    head.unknown = { keep: 1 };
    if (minor === 3) head.scaleY = 'volume';
    const body = { name: 'body_physics', bone: 'body', order: 1, rotate: 0.5, wind: 4, unknown: { keep: 2 } };
    const ik = { name: 'ik', bones: ['head'], target: 'root', order: 0, mix: 0 };
    const transform = { name: 'transform', bones: ['body'], target: 'root', order: 2, mixRotate: 0, mixX: 0, mixY: 0, mixScaleX: 0, mixScaleY: 0, mixShearY: 0 };
    fixture.skins[0].physics = ['head_physics', 'body_physics'];
    fixture.animations = { idle: { physics: { head_physics: { wind: [{ value: -250 }] }, body_physics: { wind: [{ value: 4 }] } } } };
    if (minor === 3) fixture.constraints = [{ ...ik, type: 'ik' }, { ...body, type: 'physics' }, { type: 'transform', name: 'transform', bones: ['body'], source: 'root', properties: { rotate: { to: { rotate: {} } } }, mixRotate: 0 }, head];
    else { fixture.physics.push(body); fixture.ik = [ik]; fixture.transform = [transform]; }
    await page.evaluate(d => window.__spineTool.loadSkeleton(d, 'mixed.json'), fixture);
    await page.waitForFunction(m => window.__spineTool.runtime.key === 40 + m && window.__spineTool.runtime.active, minor);

    assert.equal(await page.locator('#deleteConstraint').isDisabled(), true);
    assert.deepEqual(await list.locator('.constraint-text').allTextContents(), ['body_physics', 'head_physics']);
    await row('head_physics').click({ button: 'right' });
    assert.equal(await page.locator('#deleteConstraint').isEnabled(), true);
    assert.deepEqual(await page.locator('#constraintMenu button span').allTextContents(), ['删除', '保存该约束参数为预设', '复制物理参数', '粘贴物理参数']);
    assert.equal(await menu('paste').isDisabled(), minor === 2);
    await menu('save-preset').click();
    await page.locator('dialog input').fill('constraint-' + minor);
    await confirm();
    const preset = await page.evaluate(name => JSON.parse(localStorage.getItem('spineRigTools.physicsPresets.v1')).find(p => p.name === name), 'constraint-' + minor);
    assert.equal(preset.values.wind, -250);
    assert.equal(preset.values.mix, 1.8);
    assert.equal(preset.values.windGlobal, true);
    assert.equal(Object.hasOwn(preset.values, 'bone'), false);
    await row('head_physics').click({ button: 'right' });
    await menu('copy').click();
    await row('body_physics').click({ button: 'right' });
    await menu('paste').click();
    const pasted = await page.evaluate(() => window.constraintModel.physics(window.__spineTool.getData(), Number(window.__spineTool.getData().skeleton.spine.split('.')[1])).find(c => c.name === 'body_physics'));
    assert.equal(pasted.wind, -250);
    assert.equal(pasted.mix, 1.8);
    assert.equal(pasted.order, 1);
    assert.equal(pasted.bone, 'body');
    assert.deepEqual(pasted.unknown, { keep: 2 });
    if (minor === 3) assert.equal(pasted.scaleY, 'volume');
    await row('head_physics').click();
    await page.keyboard.press('Control+c');
    await row('body_physics').click({ modifiers: ['Control'] });
    assert.equal(await list.locator('.selected').count(), 2);
    await row('body_physics').click({ button: 'right' });
    assert.equal(await list.locator('.selected').count(), 2);
    await page.keyboard.press('Escape');
    await page.keyboard.press('Control+v');
    await row('body_physics').click();
    await row('head_physics').click({ modifiers: ['Shift'] });
    assert.equal(await list.locator('.selected').count(), 2);
    report.checks.push(`4.${minor} context actions, exact preset save, identity-safe clipboard, Ctrl/Shift multiselect`);

    const selectionBefore = await page.evaluate(() => [...window.__spineTool.selection.names]);
    assert.equal(await page.locator('#sortConstraints').textContent(), '自动排序');
    const beforeFailure = await page.evaluate(() => window.__spineTool.getData());
    for (const failure of ['parse', 'pose']) {
      await page.evaluate(mode => {
        const t=window.__spineTool,sp=t.runtime.spine;
        window.__orderFailureSaved={skeleton:t.runtime.skeleton,atlas:t.runtime.atlas,resources:t.runtime.context.restorables.length,mode};
        if(mode==='parse'){
          window.__orderFailureSaved.original=sp.SkeletonJson.prototype.readSkeletonData;
          sp.SkeletonJson.prototype.readSkeletonData=function(){throw Error('injected order parse failure')};
        }else{
          window.__orderFailureSaved.original=sp.Skeleton.prototype.updateWorldTransform;
          sp.Skeleton.prototype.updateWorldTransform=function(...args){if(this!==window.__orderFailureSaved.skeleton)throw Error('injected order pose failure');return window.__orderFailureSaved.original.apply(this,args)};
        }
      }, failure);
      await page.locator('#sortConstraints').click();
      await page.waitForSelector('dialog[open]');
      assert.match(await page.locator('dialog p').textContent(), /injected order.*原顺序未改动/s);
      assert.deepEqual(await page.evaluate(() => window.__spineTool.getData()), beforeFailure);
      assert.deepEqual(await page.evaluate(() => {const t=window.__spineTool,s=window.__orderFailureSaved;return{active:t.runtime.active,sameSkeleton:t.runtime.skeleton===s.skeleton,sameAtlas:t.runtime.atlas===s.atlas,sameResources:t.runtime.context.restorables.length===s.resources};}),{active:true,sameSkeleton:true,sameAtlas:true,sameResources:true});
      await page.evaluate(() => {
        const sp=window.__spineTool.runtime.spine,s=window.__orderFailureSaved;
        if(s.mode==='parse')sp.SkeletonJson.prototype.readSkeletonData=s.original;
        else sp.Skeleton.prototype.updateWorldTransform=s.original;
        delete window.__orderFailureSaved;
      });
      await confirm();
    }
    report.checks.push(`4.${minor} staged sorting rolls back JSON and keeps original live preview/resources on parse/pose failure`);
    await page.locator('#sortConstraints').click();
    assert.equal(await page.locator('dialog').count(), 0, 'no manual sorting dialog');
    const order = await page.evaluate(() => {
      const t = window.__spineTool, minor = Number(t.getData().skeleton.spine.split('.')[1]);
      return { data: window.constraintModel.entries(t.getData(), minor).map(e => e.constraint.name), runtime: t.runtime.skeleton._updateCache.filter(c => c.data?.name && !(c instanceof t.runtime.spine.Bone)).map(c => c.data.name) };
    });
    assert.deepEqual(order.data, ['transform', 'body_physics', 'ik', 'head_physics']);
    assert.deepEqual(order.runtime, order.data);
    assert.deepEqual(await list.locator('.constraint-text').allTextContents(), ['body_physics', 'head_physics']);
    assert.deepEqual(await page.evaluate(() => [...window.__spineTool.selection.names]), selectionBefore);
    const beforeManual = await page.evaluate(() => window.__spineTool.getData());
    await beginDrag(row('head_physics'), row('body_physics'));
    assert.equal(await list.locator('.drop-before').count(), 1);
    assert.deepEqual(await page.evaluate(() => window.__spineTool.getData()), beforeManual);
    await page.keyboard.press('Escape'); await page.mouse.up();
    assert.deepEqual(await page.evaluate(() => window.__spineTool.getData()), beforeManual);
    await beginDrag(row('head_physics'), row('body_physics'));
    const outside = await page.locator('.preview-stage').boundingBox();
    await page.mouse.move(outside.x + outside.width / 2, outside.y + outside.height / 2); await page.mouse.up();
    assert.deepEqual(await page.evaluate(() => window.__spineTool.getData()), beforeManual);
    await beginDrag(row('head_physics'), row('body_physics'));
    await list.dispatchEvent('pointercancel', { pointerId: 1 }); await page.mouse.up();
    assert.deepEqual(await page.evaluate(() => window.__spineTool.getData()), beforeManual);
    await dragPointer(row('head_physics'), row('body_physics'));
    await page.waitForFunction(() => document.querySelector('#toast').textContent.includes('顺序已调整'));
    const manuallyOrdered = await page.evaluate(() => {
      const t = window.__spineTool, m = Number(t.getData().skeleton.spine.split('.')[1]);
      return { data: window.constraintModel.entries(t.getData(), m).map(e => e.constraint.name), runtime: t.runtime.skeleton._updateCache.filter(c => c.data?.name && !(c instanceof t.runtime.spine.Bone)).map(c => c.data.name) };
    });
    assert.deepEqual(manuallyOrdered.data, ['transform', 'head_physics', 'body_physics', 'ik']);
    assert.deepEqual(manuallyOrdered.runtime, manuallyOrdered.data);
    assert.deepEqual(await list.locator('.constraint-text').allTextContents(), ['head_physics', 'body_physics']);
    assert.deepEqual(await page.evaluate(() => window.__spineTool.selection.names), ['head']);
    assert.deepEqual(await page.evaluate(() => window.__spineTool.getData().skins), beforeManual.skins);
    assert.deepEqual(await page.evaluate(() => window.__spineTool.getData().animations), beforeManual.animations);
    const manualDestination = path.join(output, 'manual-' + minor + '.json');
    await app.evaluate(({ dialog }, filePath) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath }); }, manualDestination);
    await page.locator('#exportJson').click();
    await page.waitForFunction(file => document.querySelector('#toast').textContent.includes(file), 'manual-' + minor + '.json');
    const manualExport = JSON.parse(await fs.readFile(manualDestination, 'utf8'));
    assert.deepEqual(require('../src/renderer/constraint-model.js').entries(manualExport, minor).map(e => e.constraint.name), manuallyOrdered.data);
    await dragPointer(row('head_physics'), row('body_physics'), false);
    assert.deepEqual(await list.locator('.constraint-text').allTextContents(), ['body_physics', 'head_physics']);
    report.checks.push(`4.${minor} left-drag both directions, actual runtime/export sequence, Escape/outside/cancel and data preservation`);
    await page.locator('#sortConstraints').click();
    assert.deepEqual(await page.evaluate(() => window.constraintModel.entries(window.__spineTool.getData(), Number(window.__spineTool.getData().skeleton.spine.split('.')[1])).map(e => e.constraint.name)), order.data);
    const beforeRepeat = await page.evaluate(() => window.__spineTool.getData());
    await page.locator('#sortConstraints').click();
    assert.deepEqual(await page.evaluate(() => window.__spineTool.getData()), beforeRepeat);
    const destination = path.join(output, 'sorted-' + minor + '.json');
    await app.evaluate(({ dialog }, destination) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: destination }); }, destination);
    await page.locator('#exportJson').click();
    await page.waitForFunction(() => document.querySelector('#toast').textContent.includes('已保存'));
    const exported = JSON.parse(await fs.readFile(destination, 'utf8'));
    const model = require('../src/renderer/constraint-model.js');
    assert.deepEqual(model.entries(exported, minor).map(e => e.constraint.name), order.data);
    assert.deepEqual(exported.skins, beforeRepeat.skins);
    assert.deepEqual(exported.animations, beforeRepeat.animations);
    await page.screenshot({ path: path.join(output, 'sorted-' + minor + '.png') });
    report.checks.push(`4.${minor} one-click dependency ordering, real runtime sequence, selection preserved, idempotence and native export`);

    await row('head_physics').click();
    await page.locator('#deleteConstraint').click();
    await page.locator('dialog button').filter({ hasText: '取消' }).click();
    assert.equal(await row('head_physics').count(), 1);
    await row('head_physics').click({ button: 'right' });
    await menu('delete').click();
    await confirm();
    const deleted = await page.evaluate(() => window.__spineTool.getData());
    assert.deepEqual(deleted.skins[0].physics, ['body_physics']);
    assert.deepEqual(Object.keys(deleted.animations.idle.physics), ['body_physics']);
    assert.equal(await row('head_physics').count(), 0);
    assert.equal(await page.locator('#deleteConstraint').isDisabled(), true);
    assert.equal(await page.evaluate(() => window.__spineTool.runtime.skeleton !== null), true);
    await row('body_physics').click();
    await page.keyboard.press('Delete');
    await confirm();
    assert.equal(await list.locator('.constraint-row').count(), 0);
    report.checks.push(`4.${minor} bottom-button/context/Delete deletion and cancellation, skin/timeline cleanup`);
    await page.screenshot({ path: path.join(output, 'constraints-' + minor + '.png') });
    const cycle = JSON.parse(JSON.stringify(fixture));
    for (const skin of cycle.skins) delete skin.physics;
    delete cycle.animations;
    const a = { name: 'cycle_head', bones: ['head'], target: 'body', order: 0, mixRotate: 0 };
    const b = { name: 'cycle_body', bones: ['body'], target: 'head', order: 1, mixRotate: 0 };
    if (minor === 3) cycle.constraints = [a, b].map(c => ({ type: 'transform', name: c.name, bones: c.bones, source: c.target, properties: { rotate: { to: { rotate: {} } } }, mixRotate: 0 }));
    else { cycle.ik = []; cycle.physics = []; cycle.transform = [a, b]; }
    await page.evaluate(d => window.__spineTool.loadSkeleton(d, 'cycle.json'), cycle);
    await page.waitForFunction(() => window.__spineTool.runtime.active);
    const cycleBefore = await page.evaluate(() => JSON.stringify(window.__spineTool.getData()));
    await page.locator('#sortConstraints').click();
    await page.waitForSelector('dialog[open]');
    assert.equal(await page.locator('dialog h2').textContent(), '自动排序未应用');
    assert.match(await page.locator('dialog p').textContent(), /循环依赖/);
    assert.equal(await page.evaluate(() => JSON.stringify(window.__spineTool.getData())), cycleBefore);
    assert.equal(await page.evaluate(() => window.__spineTool.runtime.active), true);
    await page.locator('dialog .primary').click();
    report.checks.push(`4.${minor} cycle is explained without changing JSON or stopping preview`);
  }
  assert.deepEqual(report.errors, []);
  report.passed = true;
}
main().catch(e => { report.passed = false; report.failure = e.stack; process.exitCode = 1; }).finally(async () => {
  if (app) await app.close().catch(() => {});
  await fs.writeFile(path.join(output, 'constraint-report.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
});